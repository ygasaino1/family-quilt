#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Person {
    pub id: String,
    pub display_name: String,
    pub sex: Sex,
    pub is_living: bool,
    pub birth: Option<FuzzyDate>,
    pub birth_place: Option<PlaceRef>,
    pub death: Option<FuzzyDate>,
    pub death_place: Option<PlaceRef>,
    pub note: Option<String>,
    pub status: Status,
    pub proposal_id: Option<String>,
    pub created_by: String,
    pub agent_note: Option<String>,
    pub created_at: String,
    pub updated_at: String,
    pub names: Vec<PersonName>,
}

impl Person {
    /// Deceased = marked not living **or** has a death date (the quilt's grey name background).
    pub fn is_deceased(&self) -> bool {
        !self.is_living || self.death.is_some()
    }
}


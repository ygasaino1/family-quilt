//! Plain data types of the store layer.

use crate::dates::{FuzzyDate, PartialDate};
use crate::error::StoreError;
use serde::Serialize;

/// Defines a text-backed enum with `as_str`, `parse` and `ALL`.
macro_rules! text_enum {
    ($(#[$m:meta])* $name:ident, $field:literal, { $($variant:ident => $text:literal),+ $(,)? }) => {
        $(#[$m])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize)]
        #[serde(rename_all = "snake_case")]
        pub enum $name { $($variant),+ }
        impl $name {
            pub const ALL: &'static [$name] = &[$($name::$variant),+];
            pub fn as_str(self) -> &'static str { match self { $($name::$variant => $text),+ } }
            pub fn parse(s: &str) -> Result<Self, StoreError> {
                match s {
                    $($text => Ok($name::$variant),)+
                    _ => Err(StoreError::invalid($field, format!("'{}' is not one of: {}", s, [$($text),+].join(", ")))),
                }
            }
        }
        impl std::fmt::Display for $name {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result { f.write_str(self.as_str()) }
        }
    };
}

text_enum!(Sex, "sex", { Male => "M", Female => "F", Other => "X", Unknown => "U" });
text_enum!(Status, "status", { Verified => "verified", Pending => "pending" });
text_enum!(NameType, "name type", { Birth => "birth", Married => "married", Alias => "alias", Religious => "religious", Other => "other" });
text_enum!(RelType, "relationship type", { ParentChild => "parent_child", Partnership => "partnership" });
text_enum!(
    /// Nature of a parent-child link (section 5).
    LinkKind, "kind",
    { Birth => "birth", Adopted => "adopted", Foster => "foster", Step => "step", Guardian => "guardian", Sealing => "sealing", Unknown => "unknown" }
);
text_enum!(
    /// State of a partnership; `divorced` and `ended` both show as "D" in the quilt header.
    PartnershipState, "subtype",
    { Married => "married", Unmarried => "unmarried", Divorced => "divorced", Ended => "ended", Unknown => "unknown" }
);

impl LinkKind {
    /// Only `birth` counts as blood. `unknown` is deliberately **not** blood.
    pub fn is_blood(self) -> bool {
        self == LinkKind::Birth
    }
}

#[allow(clippy::derivable_impls)] // enum is generated by `text_enum!`
impl Default for Sex {
    fn default() -> Self {
        Sex::Unknown
    }
}
#[allow(clippy::derivable_impls)] // enum is generated by `text_enum!`
impl Default for LinkKind {
    fn default() -> Self {
        LinkKind::Birth
    }
}
#[allow(clippy::derivable_impls)] // enum is generated by `text_enum!`
impl Default for PartnershipState {
    fn default() -> Self {
        PartnershipState::Unknown
    }
}

/// Who made a record and in what state it starts.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Origin {
    /// `"human"` or `"agent:<name>"`.
    pub created_by: String,
    pub status: Status,
    pub proposal_id: Option<String>,
    pub agent_note: Option<String>,
}

impl Origin {
    pub fn human() -> Self {
        Origin { created_by: "human".into(), status: Status::Verified, proposal_id: None, agent_note: None }
    }
    /// An agent's work is always pending until a human approves it.
    pub fn agent(name: &str, proposal_id: &str, agent_note: Option<&str>) -> Self {
        Origin { created_by: format!("agent:{name}"), status: Status::Pending, proposal_id: Some(proposal_id.to_string()), agent_note: agent_note.map(str::to_string) }
    }
}

/// Three-way field for patches: leave alone, set, or clear.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub enum Field<T> {
    #[default]
    Unchanged,
    Set(T),
    Clear,
}

// ───────────────────────────── people ─────────────────────────────

#[derive(Debug, Clone, Default)]
pub struct NewName {
    pub name_type: Option<NameType>,
    pub given: Option<String>,
    pub family: Option<String>,
    /// If absent it is composed from given + family.
    pub full_name: Option<String>,
    pub script: Option<String>,
}

impl NewName {
    pub fn new(given: &str, family: &str) -> Self {
        NewName { given: Some(given.into()), family: Some(family.into()), ..Default::default() }
    }
    pub fn full(full_name: &str) -> Self {
        NewName { full_name: Some(full_name.into()), ..Default::default() }
    }
}

#[derive(Debug, Clone, Default)]
pub struct NewPerson {
    pub sex: Sex,
    /// `None` = derive: living unless a death date is given.
    pub is_living: Option<bool>,
    pub birth: Option<FuzzyDate>,
    pub birth_place: Option<String>,
    pub death: Option<FuzzyDate>,
    pub death_place: Option<String>,
    pub note: Option<String>,
    /// The first name is the primary one. At least one is required.
    pub names: Vec<NewName>,
}

